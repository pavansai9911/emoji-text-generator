/* ------------------------------------------------------------------
   fonts.js  -  the pixel fonts used to draw the emoji art.

   '#' = draw the MAIN symbol      '.' = draw the BACKGROUND symbol

   There are TWO hand-drawn masters, not one:

     FONT_LARGE  9 wide x 12 tall   used for row counts 9 and up
     FONT_SMALL  5 wide x  7 tall   used for row counts 5 - 8

   Why two? A 5x7 grid has no room to describe a diagonal or a curve.
   The middle of an "N" gets 3 usable pixels, so blowing it up to 12
   rows turns every one of them into a 2x2 block and you get a
   staircase. Straight letters like T, F and Z survive that fine;
   N, K, W, C, G, J, Q, S do not.

   FONT_LARGE fixes it by drawing at the size the art is actually
   used at. The default row count is 12, which renders at exactly
   9 x 12, so no scaling happens at all. Diagonals step one column
   per row and bowls get real rounded corners.

   FONT_SMALL is kept for tiny row counts, where FONT_LARGE's 2px
   strokes would be squashed to 1px and the letters would fall apart.

   Design rules for FONT_LARGE:
     - strokes are 2px thick (3px for stems that must sit dead centre,
       since 2 cannot be centred in 9)
     - bowls (B C D G O P Q S) lose their corners so they read round
     - diagonals move 1 column per row wherever possible
     - every stroke stays 8-connected so nothing floats
   ------------------------------------------------------------------ */

